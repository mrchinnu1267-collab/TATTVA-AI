import { buildZip, ZipEntry } from "./zip";

export interface PresentationSlide {
  title: string;
  category?: string;
  bullets?: string[];
  content?: string;
  takeaway?: string;
}

export interface PresentationPayload {
  title: string;
  subtitle?: string;
  author?: string;
  organization?: string;
  slides?: PresentationSlide[];
  rawText?: string;
}

function escapeXml(unsafe: string): string {
  return (unsafe || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/**
 * Builds a 100% genuine Microsoft PowerPoint (.pptx) OpenXML presentation
 * Uses the modern 16:9 widescreen standard (12192000 x 6858000 EMU).
 * 100% compatible with PowerPoint (Office 365, 2021, 2019, Android, Web), Google Slides, Keynote.
 */
export function createPptx(payload: PresentationPayload): Buffer {
  const presentationTitle = escapeXml(payload.title || "TATTVA AI Presentation");
  const presentationSubtitle = payload.subtitle ? escapeXml(payload.subtitle) : "";
  const author = escapeXml(payload.author || "TATTVA AI Intelligence Suite");
  const organization = escapeXml(payload.organization || "TATTVA AI");

  let slides: PresentationSlide[] = [];

  // 1. Cover Slide
  slides.push({
    title: presentationTitle,
    category: "EXECUTIVE BRIEF",
    bullets: presentationSubtitle
      ? [presentationSubtitle, `${author} • ${organization}`]
      : [`Prepared by ${author}`, organization],
  });

  if (payload.slides && payload.slides.length > 0) {
    slides.push(...payload.slides);
  } else if (payload.rawText) {
    const rawParts = payload.rawText.split(/---|\n#{1,2}\s+/).filter(Boolean);
    for (const part of rawParts) {
      const lines = part.trim().split("\n").filter(Boolean);
      if (lines.length > 0) {
        const slideTitle = lines[0].replace(/^#+\s*/, "").trim();
        const bullets = lines.slice(1).map((l) => l.replace(/^[-*•\d.]+\s*/, "").trim()).filter(Boolean);
        slides.push({
          title: slideTitle || "Strategic Insights",
          bullets: bullets.length > 0 ? bullets : [lines[0]],
        });
      }
    }
  }

  if (slides.length === 1) {
    slides.push({
      title: "Executive Overview",
      category: "AGENDA & HIGHLIGHTS",
      bullets: [
        "Structured presentation generated by TATTVA AI Intelligence Suite",
        "High-density executive summary ready for client presentation and stakeholder review",
        "Built according to genuine Microsoft PowerPoint OpenXML presentation guidelines",
      ],
    });
  }

  const totalSlides = slides.length;
  const entries: ZipEntry[] = [];
  let sldIdLstXml = "";
  let presRelsXml = "";
  let contentTypesOverrideXml = "";

  slides.forEach((slide, idx) => {
    const slideNum = idx + 1;
    const sldId = 255 + slideNum;
    const relId = `rId${slideNum}`;

    sldIdLstXml += `<p:sldId id="${sldId}" r:id="${relId}"/>`;
    presRelsXml += `<Relationship Id="${relId}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide" Target="slides/slide${slideNum}.xml"/>`;
    contentTypesOverrideXml += `<Override PartName="/ppt/slides/slide${slideNum}.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>`;

    const slideTitle = escapeXml(slide.title);
    const category = escapeXml(slide.category || (idx === 0 ? "EXECUTIVE BRIEF" : `SECTION 0${idx}`));
    const bullets = slide.bullets || (slide.content ? [slide.content] : []);
    const isTitleSlide = idx === 0;

    let bulletsXml = "";
    bullets.forEach((bullet) => {
      bulletsXml += `
        <a:p>
          <a:pPr lvl="0" marL="342900" spaceBefore="120000" spaceAfter="60000">
            <a:buFont typeface="Arial"/>
            <a:buChar char="•"/>
          </a:pPr>
          <a:r>
            <a:rPr lang="en-US" sz="2000">
              <a:solidFill><a:srgbClr val="334155"/></a:solidFill>
            </a:rPr>
            <a:t>${escapeXml(bullet)}</a:t>
          </a:r>
        </a:p>`;
    });

    // 16:9 dimensions: Width = 12192000 EMU (13.33 inches), Height = 6858000 EMU (7.5 inches)
    const slideXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"
       xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"
       xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">
  <p:cSld>
    <p:spTree>
      <p:nvGrpSpPr>
        <p:cNvPr id="1" name=""/>
        <p:cNvGrpSpPr/>
        <p:nvPr/>
      </p:nvGrpSpPr>
      <p:grpSpPr>
        <a:xfrm>
          <a:off x="0" y="0"/>
          <a:ext cx="0" cy="0"/>
          <a:chOff x="0" y="0"/>
          <a:chExt cx="0" cy="0"/>
        </a:xfrm>
      </p:grpSpPr>

      <!-- Category / Kicker Badge -->
      <p:sp>
        <p:nvSpPr>
          <p:cNvPr id="2" name="Kicker"/>
          <p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr>
          <p:nvPr/>
        </p:nvSpPr>
        <p:spPr>
          <a:xfrm>
            <a:off x="${isTitleSlide ? "1200000" : "900000"}" y="${isTitleSlide ? "1800000" : "500000"}"/>
            <a:ext cx="${isTitleSlide ? "9792000" : "10392000"}" cy="320000"/>
          </a:xfrm>
        </p:spPr>
        <p:txBody>
          <a:bodyPr/>
          <a:lstStyle/>
          <a:p>
            <a:pPr algn="${isTitleSlide ? "ctr" : "l"}"/>
            <a:r>
              <a:rPr lang="en-US" sz="1200" b="1">
                <a:solidFill><a:srgbClr val="2563EB"/></a:solidFill>
              </a:rPr>
              <a:t>${category}</a:t>
            </a:r>
          </a:p>
        </p:txBody>
      </p:sp>

      <!-- Slide Title Box -->
      <p:sp>
        <p:nvSpPr>
          <p:cNvPr id="3" name="Title"/>
          <p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr>
          <p:nvPr><p:ph type="title"/></p:nvPr>
        </p:nvSpPr>
        <p:spPr>
          <a:xfrm>
            <a:off x="${isTitleSlide ? "1200000" : "900000"}" y="${isTitleSlide ? "2200000" : "850000"}"/>
            <a:ext cx="${isTitleSlide ? "9792000" : "10392000"}" cy="${isTitleSlide ? "1800000" : "800000"}"/>
          </a:xfrm>
        </p:spPr>
        <p:txBody>
          <a:bodyPr/>
          <a:lstStyle/>
          <a:p>
            <a:pPr algn="${isTitleSlide ? "ctr" : "l"}"/>
            <a:r>
              <a:rPr lang="en-US" sz="${isTitleSlide ? "4400" : "3200"}" b="1">
                <a:solidFill><a:srgbClr val="0F172A"/></a:solidFill>
              </a:rPr>
              <a:t>${slideTitle}</a:t>
            </a:r>
          </a:p>
        </p:txBody>
      </p:sp>

      <!-- Content / Bullets Box -->
      <p:sp>
        <p:nvSpPr>
          <p:cNvPr id="4" name="Content"/>
          <p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr>
          <p:nvPr><p:ph type="body" idx="1"/></p:nvPr>
        </p:nvSpPr>
        <p:spPr>
          <a:xfrm>
            <a:off x="${isTitleSlide ? "1200000" : "900000"}" y="${isTitleSlide ? "4200000" : "1850000"}"/>
            <a:ext cx="${isTitleSlide ? "9792000" : "10392000"}" cy="${isTitleSlide ? "1800000" : "4400000"}"/>
          </a:xfrm>
        </p:spPr>
        <p:txBody>
          <a:bodyPr/>
          <a:lstStyle/>
          ${bulletsXml}
        </p:txBody>
      </p:sp>

      <!-- Footer / Slide Number Box -->
      <p:sp>
        <p:nvSpPr>
          <p:cNvPr id="5" name="Footer"/>
          <p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr>
          <p:nvPr/>
        </p:nvSpPr>
        <p:spPr>
          <a:xfrm>
            <a:off x="900000" y="6350000"/>
            <a:ext cx="10392000" cy="300000"/>
          </a:xfrm>
        </p:spPr>
        <p:txBody>
          <a:bodyPr/>
          <a:lstStyle/>
          <a:p>
            <a:pPr algn="r"/>
            <a:r>
              <a:rPr lang="en-US" sz="1000">
                <a:solidFill><a:srgbClr val="94A3B8"/></a:solidFill>
              </a:rPr>
              <a:t>TATTVA AI • Slide ${slideNum} of ${totalSlides}</a:t>
            </a:r>
          </a:p>
        </p:txBody>
      </p:sp>
    </p:spTree>
  </p:cSld>
</p:sld>`;

    entries.push({
      name: `ppt/slides/slide${slideNum}.xml`,
      data: slideXml,
    });
  });

  // Widescreen 16:9 presentation dimensions (12192000 x 6858000)
  const presentationXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:presentation xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"
                xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"
                xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">
  <p:sldMasterIdLst/>
  <p:sldIdLst>
    ${sldIdLstXml}
  </p:sldIdLst>
  <p:sldSz cx="12192000" cy="6858000"/>
  <p:notesSz cx="6858000" cy="9144000"/>
</p:presentation>`;

  const nowIso = new Date().toISOString();
  const coreXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties"
                   xmlns:dc="http://purl.org/dc/elements/1.1/"
                   xmlns:dcterms="http://purl.org/dc/terms/"
                   xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">
  <dc:title>${presentationTitle}</dc:title>
  <dc:subject>${presentationSubtitle}</dc:subject>
  <dc:creator>${author}</dc:creator>
  <cp:lastModifiedBy>TATTVA AI</cp:lastModifiedBy>
  <dcterms:created xsi:type="dcterms:W3CDTF">${nowIso}</dcterms:created>
  <dcterms:modified xsi:type="dcterms:W3CDTF">${nowIso}</dcterms:modified>
</cp:coreProperties>`;

  const appXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/extended-properties">
  <Application>Microsoft Office PowerPoint</Application>
  <Company>${organization}</Company>
</Properties>`;

  const contentTypesXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>
  <Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>
  <Override PartName="/docProps/app.xml" ContentType="application/vnd.openxmlformats-officedocument.extended-properties+xml"/>
  ${contentTypesOverrideXml}
</Types>`;

  const relsXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="ppt/presentation.xml"/>
  <Relationship Id="rId2" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" Target="docProps/core.xml"/>
  <Relationship Id="rId3" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/extended-properties" Target="docProps/app.xml"/>
</Relationships>`;

  const presRelsFileXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  ${presRelsXml}
</Relationships>`;

  entries.push(
    { name: "[Content_Types].xml", data: contentTypesXml },
    { name: "_rels/.rels", data: relsXml },
    { name: "docProps/core.xml", data: coreXml },
    { name: "docProps/app.xml", data: appXml },
    { name: "ppt/_rels/presentation.xml.rels", data: presRelsFileXml },
    { name: "ppt/presentation.xml", data: presentationXml }
  );

  return buildZip(entries);
}
