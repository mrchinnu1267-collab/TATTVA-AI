    @staticmethod
    def generate_pdf(title: str, sections: List[Dict[str, Any]], tables: Optional[List[Dict[str, Any]]] = None) -> bytes:
        """Generate high-fidelity PDF with ReportLab."""
        buffer = BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            'DocTitle',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=24,
            leading=28,
            textColor=colors.HexColor('#09090B'),
            spaceAfter=12,
        )
        subtitle_style = ParagraphStyle(
            'DocSubtitle',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=11,
            leading=16,
            textColor=colors.HexColor('#71717A'),
            spaceAfter=20,
        )
        h1_style = ParagraphStyle(
            'DocH1',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=16,
            leading=20,
            textColor=colors.HexColor('#18181B'),
            spaceBefore=16,
            spaceAfter=8,
            keepWithNext=True,
        )
        h2_style = ParagraphStyle(
            'DocH2',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=12,
            leading=16,
            textColor=colors.HexColor('#27272A'),
            spaceBefore=12,
            spaceAfter=6,
            keepWithNext=True,
        )
        body_style = ParagraphStyle(
            'DocBody',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=10,
            leading=15,
            textColor=colors.HexColor('#3F3F46'),
            spaceAfter=8,
        )
        bullet_style = ParagraphStyle(
            'DocBullet',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=10,
            leading=14,
            textColor=colors.HexColor('#27272A'),
            leftIndent=14,
            firstLineIndent=-10,
            spaceAfter=4,
        )

        story = []

        # Document Header Banner
        story.append(Paragraph(title, title_style))
        story.append(Paragraph(f"Generated on {time.strftime('%B %d, %Y')} • Powered by TATTVA AI", subtitle_style))
        story.append(Spacer(1, 10))

        # Render Content Sections
        for sec in sections:
            heading = sec.get("heading", "")
            if heading:
                story.append(Paragraph(heading, h1_style))
            
            content = sec.get("content", "")
            if content:
                for para in content.split("\n\n"):
                    trimmed = para.strip()
                    if trimmed.startswith("- ") or trimmed.startswith("* "):
                        for item in trimmed.split("\n"):
                            bullet_text = item.lstrip("-* ").strip()
                            story.append(Paragraph(f"• {bullet_text}", bullet_style))
                    elif trimmed:
                        story.append(Paragraph(trimmed, body_style))

            # Inline table if specified
            if "table" in sec and sec["table"]:
                story.append(Spacer(1, 6))
                t_data = sec["table"]
                reportlab_table = Table(t_data, hAlign='LEFT')
                reportlab_table.setStyle(TableStyle([
                    ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#18181B')),
                    ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                    ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                    ('FONTSIZE', (0, 0), (-1, 0), 9),
                    ('BOTTOMPADDING', (0, 0), (-1, 0), 6),
                    ('TOPPADDING', (0, 0), (-1, 0), 6),
                    ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E4E4E7')),
                    ('FONTNAME', (0, 1), (-1, -1), 'Helvetica'),
                    ('FONTSIZE', (0, 1), (-1, -1), 9),
                    ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#F4F4F5')]),
                    ('LEFTPADDING', (0, 0), (-1, -1), 8),
                    ('RIGHTPADDING', (0, 0), (-1, -1), 8),
                    ('TOPPADDING', (0, 1), (-1, -1), 5),
                    ('BOTTOMPADDING', (0, 1), (-1, -1), 5),
                ]))
                story.append(reportlab_table)
                story.append(Spacer(1, 10))

        # Standalone tables if any
        if tables:
            for tbl in tables:
                tbl_title = tbl.get("title", "")
                if tbl_title:
                    story.append(Paragraph(tbl_title, h2_style))
                data = tbl.get("data", [])
                if data:
                    t = Table(data, hAlign='LEFT')
                    t.setStyle(TableStyle([
                        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#27272A')),
                        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                        ('FONTSIZE', (0, 0), (-1, 0), 9),
                        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E4E4E7')),
                        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#F4F4F5')]),
                    ]))
                    story.append(t)
                    story.append(Spacer(1, 12))

        doc.build(story, canvasmaker=NumberedCanvas)
        return buffer.getvalue()

    @staticmethod
    def generate_docx(title: str, sections: List[Dict[str, Any]], tables: Optional[List[Dict[str, Any]]] = None) -> bytes:
        """Generate professionally formatted Microsoft Word DOCX document."""
        doc = docx.Document()

        # Set 1-inch margins
        for section in doc.sections:
            section.top_margin = Inches(1)
            section.bottom_margin = Inches(1)
            section.left_margin = Inches(1)
            section.right_margin = Inches(1)

            # Header and Footer
            header = section.header
            hp = header.paragraphs[0]
            hp.text = "TATTVA AI • Professional Document Suite"
            hp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            hp.style.font.size = Pt(8.5)
            hp.style.font.color.rgb = RGBColor(150, 150, 150)

            footer = section.footer
            fp = footer.paragraphs[0]
            fp.text = "Confidential • Created with TATTVA AI"
            fp.alignment = WD_ALIGN_PARAGRAPH.LEFT
            fp.style.font.size = Pt(8.5)
            fp.style.font.color.rgb = RGBColor(150, 150, 150)

        # Document Title
        p_title = doc.add_paragraph()
        run_title = p_title.add_run(title)
        run_title.font.name = "Arial"
        run_title.font.size = Pt(24)
        run_title.font.bold = True
        run_title.font.color.rgb = RGBColor(24, 24, 27)

        # Subtitle / Date
        p_sub = doc.add_paragraph()
        run_sub = p_sub.add_run(f"Generated on {time.strftime('%B %d, %Y')} • TATTVA AI")
        run_sub.font.name = "Arial"
        run_sub.font.size = Pt(10)
        run_sub.font.color.rgb = RGBColor(113, 113, 122)

        doc.add_paragraph().paragraph_format.space_after = Pt(12)

        # Sections
        for sec in sections:
            heading = sec.get("heading", "")
            if heading:
                h = doc.add_heading(level=1)
                hrun = h.add_run(heading)
                hrun.font.name = "Arial"
                hrun.font.size = Pt(15)
                hrun.font.bold = True
                hrun.font.color.rgb = RGBColor(39, 39, 42)

            content = sec.get("content", "")
            if content:
                for para in content.split("\n\n"):
                    trimmed = para.strip()
                    if trimmed.startswith("- ") or trimmed.startswith("* "):
                        for item in trimmed.split("\n"):
                            doc.add_paragraph(item.lstrip("-* ").strip(), style='List Bullet')
                    elif trimmed:
                        p = doc.add_paragraph(trimmed)
                        p.paragraph_format.line_spacing = 1.15
                        p.paragraph_format.space_after = Pt(6)

            # Table in section
            if "table" in sec and sec["table"]:
                data = sec["table"]
                rows = len(data)
                cols = len(data[0]) if rows > 0 else 0
                if rows and cols:
                    tbl = doc.add_table(rows=rows, cols=cols)
                    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
                    for r_idx, row in enumerate(data):
                        for c_idx, val in enumerate(row):
                            cell = tbl.cell(r_idx, c_idx)
                            cell.text = str(val)
                            p = cell.paragraphs[0]
                            p.paragraph_format.space_after = Pt(2)
                            p.paragraph_format.space_before = Pt(2)
                            if r_idx == 0:
                                for run in p.runs:
                                    run.font.bold = True
                                    run.font.color.rgb = RGBColor(24, 24, 27)

        buffer = BytesIO()
        doc.save(buffer)
        return buffer.getvalue()

    @staticmethod
    def generate_pptx(title: str, subtitle: str, slides_data: List[Dict[str, Any]]) -> bytes:
        """Generate sleek 16:9 PowerPoint presentation with python-pptx."""
        prs = Presentation()
        # Set 16:9 widescreen
        prs.slide_width = PPTXInches(13.333)
        prs.slide_height = PPTXInches(7.5)

        blank_layout = prs.slide_layouts[6]

        # 1. Title Slide
        slide = prs.slides.add_slide(blank_layout)
        tb = slide.shapes.add_textbox(PPTXInches(1.2), PPTXInches(2.2), PPTXInches(10.9), PPTXInches(3.2))
        tf = tb.text_frame
        tf.word_wrap = True

        p1 = tf.paragraphs[0]
        p1.text = title
        p1.font.name = "Arial"
        p1.font.size = PPTXPt(40)
        p1.font.bold = True
        p1.font.color.rgb = PPTXRGBColor(24, 24, 27)

        p2 = tf.add_paragraph()
        p2.text = subtitle or "Professional Presentation • TATTVA AI"
        p2.font.name = "Arial"
        p2.font.size = PPTXPt(18)
        p2.font.color.rgb = PPTXRGBColor(113, 113, 122)
        p2.space_before = PPTXPt(14)

        # 2. Content Slides
        for s_idx, s_info in enumerate(slides_data):
            c_slide = prs.slides.add_slide(blank_layout)

            # Slide Header
            header_tb = c_slide.shapes.add_textbox(PPTXInches(1.0), PPTXInches(0.8), PPTXInches(11.3), PPTXInches(1.0))
            h_tf = header_tb.text_frame
            h_p = h_tf.paragraphs[0]
            h_p.text = s_info.get("title", f"Slide {s_idx + 2}")
            h_p.font.name = "Arial"
            h_p.font.size = PPTXPt(26)
            h_p.font.bold = True
            h_p.font.color.rgb = PPTXRGBColor(24, 24, 27)

            bullets = s_info.get("bullets", [])
            content_text = s_info.get("content", "")

            # Content container
            content_tb = c_slide.shapes.add_textbox(PPTXInches(1.0), PPTXInches(2.0), PPTXInches(11.3), PPTXInches(4.5))
            c_tf = content_tb.text_frame
            c_tf.word_wrap = True

            if bullets:
                for b_idx, bullet in enumerate(bullets):
                    bp = c_tf.paragraphs[0] if b_idx == 0 else c_tf.add_paragraph()
                    bp.text = f"•  {bullet}"
                    bp.font.name = "Arial"
                    bp.font.size = PPTXPt(16)
                    bp.font.color.rgb = PPTXRGBColor(63, 63, 70)
                    bp.space_before = PPTXPt(10)
            elif content_text:
                for para in content_text.split("\n\n"):
                    cp = c_tf.add_paragraph()
                    cp.text = para
                    cp.font.name = "Arial"
                    cp.font.size = PPTXPt(15)
                    cp.font.color.rgb = PPTXRGBColor(63, 63, 70)
                    cp.space_before = PPTXPt(8)

        buffer = BytesIO()
        prs.save(buffer)
        return buffer.getvalue()

    @staticmethod
    def generate_xlsx(sheets_data: List[Dict[str, Any]]) -> bytes:
        """Generate Excel workbook with multiple sheets, formulas, and styled tables."""
        wb = openpyxl.Workbook()
        # Remove default sheet
        wb.remove(wb.active)

        header_font = Font(name="Arial", size=11, bold=True, color="FFFFFF")
        header_fill = PatternFill(start_color="18181B", end_color="18181B", fill_type="solid")
        zebra_fill = PatternFill(start_color="F4F4F5", end_color="F4F4F5", fill_type="solid")
        thin_border = Border(
            left=Side(style='thin', color="E4E4E7"),
            right=Side(style='thin', color="E4E4E7"),
            top=Side(style='thin', color="E4E4E7"),
            bottom=Side(style='thin', color="E4E4E7"),
        )

        for s_idx, s_info in enumerate(sheets_data):
            title = s_info.get("title", f"Sheet{s_idx + 1}")[:31] # Excel max 31 chars
            ws = wb.create_sheet(title=title)
            ws.views.sheetView[0].showGridLines = True

            rows = s_info.get("rows", [])
            for r_idx, row in enumerate(rows, start=1):
                for c_idx, val in enumerate(row, start=1):
                    cell = ws.cell(row=r_idx, column=c_idx, value=val)
                    cell.font = Font(name="Arial", size=10)
                    cell.border = thin_border

                    # Header styling
                    if r_idx == 1:
                        cell.font = header_font
                        cell.fill = header_fill
                        cell.alignment = Alignment(horizontal="center", vertical="center")
                    elif r_idx % 2 == 0:
                        cell.fill = zebra_fill

            # Apply formulas if provided in config
            formulas = s_info.get("formulas", [])
            for f in formulas:
                f_cell = ws[f["cell"]]
                f_cell.value = f["formula"]
                f_cell.font = Font(name="Arial", size=10, bold=True)

            # Auto-fit column widths
            for col in ws.columns:
                max_len = max(len(str(cell.value or "")) for cell in col)
                col_letter = get_column_letter(col[0].column)
                ws.column_dimensions[col_letter].width = max(max_len + 4, 12)

        buffer = BytesIO()
        wb.save(buffer)
        return buffer.getvalue()

    @staticmethod
    def generate_csv(data: List[List[Any]]) -> bytes:
        """Generate clean CSV using pandas with proper escaping."""
        if not data:
            return b""
        header = data[0]
        rows = data[1:]
        df = pd.DataFrame(rows, columns=header)
        buffer = BytesIO()
        df.to_csv(buffer, index=False, encoding='utf-8')
        return buffer.getvalue()
